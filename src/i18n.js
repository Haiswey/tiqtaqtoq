export const LANGS = [
  { id: 'en', label: 'English' },
  { id: 'ms', label: 'BM' },
  { id: 'zh', label: '中文' },
];

let lang = 'en';
try { lang = localStorage.getItem('tqt-lang') || 'en'; } catch (e) { /* private mode */ }
if (!STR[lang]) lang = 'en';

export function getLang() { return lang; }

export function setLang(id) {
  if (!STR[id]) return;
  lang = id;
  try { localStorage.setItem('tqt-lang', id); } catch (e) { /* private mode */ }
  document.documentElement.lang = id === 'zh' ? 'zh' : id;
}

export function t(key, vars = {}) {
  const s = STR[lang][key] ?? STR.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}
